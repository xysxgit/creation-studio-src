import { chromium } from 'playwright';
const CHROME = '/root/.cache/ms-playwright/chromium-1234/chrome-linux/chrome';
const browser = await chromium.launch({ headless: true, executablePath: CHROME, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const ctx = await browser.newContext({ viewport: { width: 812, height: 375 } });
const page = await ctx.newPage();
await page.goto('http://localhost:8787/');
await page.waitForSelector('.welcome', { timeout: 8000 });
await page.evaluate(() => { localStorage.setItem('cs.helpSeen', '1'); });
await page.reload();
await page.waitForSelector('.welcome');
await page.click('text=＋ 新建项目');
await page.click('.type-card:has-text("小说")');
await page.click('.modal-actions .btn.primary');
await page.waitForSelector('.canvas-wrap');
await page.waitForTimeout(500);
await page.click('.tb-collapse-btn');
await page.waitForTimeout(300);
await page.click('.tb-menu-icon');
await page.waitForTimeout(400);
const open = await page.evaluate(() => document.querySelector('.sidebar-left').classList.contains('open'));
console.log('横屏折叠后☰打开侧栏:', open ? '✅' : '❌');
await page.click('.sidebar-sheet-mask, .sidebar-left .sb-close, .drawer-mask').catch(() => {});
await page.waitForTimeout(200);
await page.click('.tb-inspire-icon').catch(() => {});
await page.waitForTimeout(400);
const rightOpen = await page.evaluate(() => document.querySelector('.sidebar-right')?.classList.contains('open'));
console.log('横屏折叠后💡打开右栏:', rightOpen ? '✅' : '❌');
await browser.close();
process.exit(0);